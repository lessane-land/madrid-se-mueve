#!/usr/bin/env python3
"""
bay_index.py · writes the page for bayarea.lessane.es from this repo's index.html.

The Bay edition runs the same code as Madrid: its repo (lessane-land/bay-area-se-mueve) holds only this page
and a CNAME. Scripts, styles, fonts and icons load from https://madrid.lessane.es/, so every change here
reaches the Bay too. Run this again only when index.html changes.

Usage: python3 scripts/bay_index.py path/to/bay-area-se-mueve
"""
import json
import os
import re
import sys

BASE = "https://madrid.lessane.es/"
TITLE = "Bay Area se mueve"
DESC_EN = "The SF Bay Area, live: BART, Muni, Caltrain, ferries, every bus and every Bay Wheels station."


def main() -> int:
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "bay"
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    s = open(os.path.join(here, "index.html"), encoding="utf-8").read()

    # Assets from the Madrid site (relative src and href only; hashes and absolute URLs stay).
    s = re.sub(r'(src|href)="(?!https?:|#|/|data:)([^"]+)"', lambda m: f'{m.group(1)}="{BASE}{m.group(2)}"', s)

    s = s.replace('<html lang="es">', '<html lang="en">', 1)
    s = s.replace("<!-- Madrid edition. bayarea.lessane.es serves a copy of this page from the bay-area-se-mueve repo (scripts/bay_index.py). -->",
                  "<!-- Generated by scripts/bay_index.py in lessane-land/madrid-se-mueve. Do not edit here. -->", 1)
    s = s.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="msm-city" content="bay">', 1)
    s = re.sub(r"<title>[^<]*</title>", f"<title>{TITLE}</title>", s, count=1)
    meta = {
        'name="description"': DESC_EN,
        'property="og:title"': TITLE,
        'property="og:description"': DESC_EN,
        'property="og:url"': "https://bayarea.lessane.es/",
        'property="og:image"': BASE + "og-bay.jpg",
        'property="og:image:alt"': "The Bay Area drawn by its Bay Wheels stations and its trains, with the free bikes in big type",
        'property="og:locale"': "en_US",
    }
    for key, value in meta.items():
        s, n = re.subn(rf'<meta {key} content="[^"]*">', f'<meta {key} content="{value}">', s, count=1)
        if not n:
            print(f"missing meta {key}", file=sys.stderr)
            return 1
    # Its own install manifest, so Add to Home Screen opens the Bay, not Madrid.
    s = s.replace(f'<link rel="manifest" href="{BASE}manifest.webmanifest">', '<link rel="manifest" href="manifest.webmanifest">', 1)
    s = s.replace('<meta name="apple-mobile-web-app-title" content="Madrid se mueve">', f'<meta name="apple-mobile-web-app-title" content="{TITLE}">', 1)
    s = s.replace('<a class="brand" href="#pulso" data-es="{title}">Madrid se mueve</a>',
                  '<a class="brand" href="#pulso" data-es="{title}">Bay Area se mueve</a>', 1)

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "index.html"), "w", encoding="utf-8") as f:
        f.write(s)
    manifest = {
        "name": TITLE, "short_name": "Bay se mueve", "description": DESC_EN, "start_url": "./#pulso",
        "display": "standalone", "display_override": ["fullscreen", "standalone"],
        "background_color": "#0A0A0A", "theme_color": "#0A0A0A", "lang": "en",
        "icons": [{"src": BASE + "icon-192.png", "sizes": "192x192", "type": "image/png"},
                  {"src": BASE + "icon-512.png", "sizes": "512x512", "type": "image/png"}],
    }
    with open(os.path.join(out_dir, "manifest.webmanifest"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2); f.write("\n")
    with open(os.path.join(out_dir, "CNAME"), "w") as f:
        f.write("bayarea.lessane.es\n")
    print(f"{out_dir}/index.html, manifest.webmanifest and CNAME written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
